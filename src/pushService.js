/**
 * Asks for notification permission (if needed), creates a push subscription,
 * and saves it to the push_subscriptions table linked to this order.
 *
 * RETURNS:
 *   { ok: true }                            — subscribed successfully
 *   { ok: false, reason: "unsupported" }    — device can't do push at all
 *   { ok: false, reason: "denied" }         — patron blocked notifications
 *   { ok: false, reason: "no_vapid_key" }   — VAPID_PUBLIC_KEY not set (dev oops)
 *   { ok: false, reason: "subscribe_failed", error } — browser refused
 *   { ok: false, reason: "save_failed", error }     — DB insert errored
 *
 * The caller (App.jsx confirmation screen) decides what UI to show based on
 * the reason. We return structured failures instead of throwing because
 * "patron tapped Block" isn't really an exception — it's a normal outcome.
 *
 * SAFETY:
 *   - Idempotent: calling it twice for the same (order, device) is a no-op
 *     thanks to the unique index on (order_id, endpoint) in the DB.
 *   - Reuses an existing PushSubscription if the browser already has one
 *     for this domain — doesn't force the browser to mint a new one.
 */
export async function subscribeOrderToPush({ orderId, venueId }) {
  if (!isPushSupported()) {
    return { ok: false, reason: "unsupported" };
  }
  if (!VAPID_PUBLIC_KEY || VAPID_PUBLIC_KEY.startsWith("REPLACE_ME")) {
    console.error("VAPID_PUBLIC_KEY not configured in pushService.js");
    return { ok: false, reason: "no_vapid_key" };
  }
  if (!orderId || !venueId) {
    return { ok: false, reason: "missing_args" };
  }

  // Permission gate. If denied, we can't ask again — the browser silently
  // refuses requestPermission() calls after a denial.
  if (Notification.permission === "denied") {
    return { ok: false, reason: "denied" };
  }
  if (Notification.permission === "default") {
    const result = await Notification.requestPermission();
    if (result !== "granted") {
      return { ok: false, reason: "denied" };
    }
  }
  // At this point we have permission. Proceed.

  // Get the active service worker registration. sw.js was registered in
  // main.jsx at app startup, so this should resolve immediately.
  let registration;
  try {
    registration = await navigator.serviceWorker.ready;
  } catch (err) {
    console.error("Service worker not ready:", err);
    return { ok: false, reason: "subscribe_failed", error: err };
  }

  // Try to reuse an existing subscription for this device first. If the
  // patron has subscribed on a previous order, the browser still has the
  // subscription object — we don't need to mint a new one, just link it
  // to the new order_id in our DB.
  let subscription;
  try {
    subscription = await registration.pushManager.getSubscription();
    if (!subscription) {
      subscription = await registration.pushManager.subscribe({
        userVisibleOnly: true,
        applicationServerKey: urlBase64ToUint8Array(VAPID_PUBLIC_KEY),
      });
    }
  } catch (err) {
    console.error("PushManager.subscribe failed:", err);
    return { ok: false, reason: "subscribe_failed", error: err };
  }

  // Extract the parts our DB needs
  const subJson = subscription.toJSON();
  const endpoint = subJson.endpoint;
  const p256dh = subJson.keys?.p256dh;
  const auth = subJson.keys?.auth;

  if (!endpoint || !p256dh || !auth) {
    console.error("Subscription missing required fields:", subJson);
    return { ok: false, reason: "subscribe_failed" };
  }

  // Save it to Supabase. The unique index on (order_id, endpoint) means a
  // duplicate insert (e.g. patron tapped twice) will fail with a 409 — we
  // catch that and treat it as success since "already subscribed" is fine.
  const { error: insertErr } = await supabase
    .from("push_subscriptions")
    .insert({
      order_id: orderId,
      venue_id: venueId,
      endpoint,
      p256dh_key: p256dh,
      auth_key: auth,
      user_agent: typeof navigator !== "undefined" ? navigator.userAgent : null,
    });

  if (insertErr) {
    // 23505 = unique violation = "already exists" = fine, this device is already
    // subscribed for this order. Treat as success.
    if (insertErr.code === "23505") {
      return { ok: true, alreadySubscribed: true };
    }
    console.error("push_subscriptions insert failed:", insertErr);
    return { ok: false, reason: "save_failed", error: insertErr };
  }

  return { ok: true };
}

