/**
 * Returns true if this browser can receive web push notifications.
 *
 * The check is intentionally conservative: a device passes only if ALL of
 * 'serviceWorker', 'PushManager', and 'Notification' APIs exist. iOS Safari
 * lies about some of these in unusual states (e.g. private browsing), so
 * we re-check at subscribe time too.
 */
export function isPushSupported() {
  if (typeof window === "undefined") return false;
  return (
    "serviceWorker" in navigator &&
    "PushManager" in window &&
    "Notification" in window
  );
}

/**
 * Returns the current notification permission state for this origin.
 * Possible values:
 *   "default" — patron has never been asked; safe to prompt
 *   "granted" — patron previously said yes
 *   "denied"  — patron previously said no; cannot prompt again (browser
 *               will silently ignore requestPermission() calls)
 *   "unsupported" — push not available on this device at all
 */
export function getPermissionState() {
  if (!isPushSupported()) return "unsupported";
  return Notification.permission;
}

// ============================================================================
// VAPID KEY HELPER
// ============================================================================

/**
 * The browser's pushManager.subscribe() needs the VAPID public key as a
 * Uint8Array, not a base64url string. This converts it.
 *
 * Standard helper recommended by every web-push tutorial. Lifted as-is
 * because the math is annoying and easy to get subtly wrong.
 */
function urlBase64ToUint8Array(base64String) {
  const padding = "=".repeat((4 - (base64String.length % 4)) % 4);
  const base64 = (base64String + padding).replace(/-/g, "+").replace(/_/g, "/");
  const rawData = atob(base64);
  const outputArray = new Uint8Array(rawData.length);
  for (let i = 0; i < rawData.length; ++i) {
    outputArray[i] = rawData.charCodeAt(i);
  }
  return outputArray;
}

