/**
 * ============================================
 * WAITLESS — Push Notification Client Service
 * ============================================
 *
 * FILE: src/lib/pushService.js
 *
 * Handles the patron-side push subscription flow:
 *   1. Detect whether this browser supports web push
 *   2. Ask the patron for notification permission (if not already decided)
 *   3. Subscribe to the browser's push manager
 *   4. POST the subscription to our DB so send-push.js can target this device
 *
 * Imported by App.jsx on the confirmation screen.
 *
 * BROWSER SUPPORT REALITY:
 *   - Desktop Chrome/Edge/Firefox/Safari 16+      → works fine
 *   - Android Chrome/Firefox                      → works fine
 *   - iOS Safari (browser tab)                    → push NOT supported, period
 *   - iOS Safari (PWA installed to home screen)   → works since iOS 16.4
 *
 * We use isPushSupported() to detect upfront and hide the "Enable
 * notifications" button on devices where it won't work — better than
 * silently failing or showing a confusing error.
 *
 * ============================================
 * IMPORTANT: VAPID public key must match what's in Netlify env vars
 * (VAPID_PUBLIC_KEY). If they don't match, browsers will accept the
 * subscription but send-push.js won't be able to deliver notifications.
 * ============================================
 */

